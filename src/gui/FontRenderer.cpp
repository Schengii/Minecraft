FontRenderer::FontRenderer() {
    init();
}

FontRenderer::~FontRenderer() {
    if (m_FontTexture && glDeleteTextures) {
        glDeleteTextures(1, &m_FontTexture);
    }
    if (m_VAO && glDeleteVertexArrays) {
        glDeleteVertexArrays(1, &m_VAO);
    }
    if (m_VBO && glDeleteBuffers) {
        glDeleteBuffers(1, &m_VBO);
    }
}

FontRenderer& FontRenderer::getInstance() {
    static FontRenderer instance;
    return instance;
}

void FontRenderer::init() {
    if (m_IsInitialized) return;
    if (!glCreateShader || !glGenVertexArrays) return;

    m_Shader = std::make_unique<Shader>("assets/shaders/ui.vert", "assets/shaders/ui.frag");

    generateFontAtlas();

    if (glGenVertexArrays && glGenBuffers) {
        glGenVertexArrays(1, &m_VAO);
        glGenBuffers(1, &m_VBO);

        glBindVertexArray(m_VAO);
        glBindBuffer(GL_ARRAY_BUFFER, m_VBO);
        // Reserve buffer space for dynamic text quad vertices
        glBufferData(GL_ARRAY_BUFFER, sizeof(float) * 6 * 4 * 256, nullptr, GL_DYNAMIC_DRAW);

        glEnableVertexAttribArray(0); // Pos (vec2)
        glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)0);

        glEnableVertexAttribArray(1); // TexCoord (vec2)
        glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, 4 * sizeof(float), (void*)(2 * sizeof(float)));

        glBindVertexArray(0);
    }

    m_IsInitialized = true;
}

void FontRenderer::resize(int windowWidth, int windowHeight) {
    m_WindowWidth = windowWidth;
    m_WindowHeight = windowHeight;
}

void FontRenderer::generateFontAtlas() {
    if (!glGenTextures) return;

    // 16x16 grid of 8x8 glyphs -> 128x128 atlas texture
    const int ATLAS_SIZE = 128;
    std::vector<uint8_t> atlas(ATLAS_SIZE * ATLAS_SIZE * 4, 0);

    for (int i = 0; i < 95; ++i) {
        int tileX = (i % 16) * 8;
        int tileY = (i / 16) * 8;

        for (int row = 0; row < 8; ++row) {
            uint8_t rowBits = GLYPH_DATA[i][row];
            for (int col = 0; col < 8; ++col) {
                bool isSet = (rowBits & (0x80 >> col)) != 0;
                int px = tileX + col;
                int py = tileY + row;
                int idx = (py * ATLAS_SIZE + px) * 4;

                if (isSet) {
                    atlas[idx + 0] = 255;
                    atlas[idx + 1] = 255;
                    atlas[idx + 2] = 255;
                    atlas[idx + 3] = 255;
                } else {
                    atlas[idx + 0] = 0;
                    atlas[idx + 1] = 0;
                    atlas[idx + 2] = 0;
                    atlas[idx + 3] = 0;
                }
            }
        }
    }

    glGenTextures(1, &m_FontTexture);
    glBindTexture(GL_TEXTURE_2D, m_FontTexture);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, ATLAS_SIZE, ATLAS_SIZE, 0, GL_RGBA, GL_UNSIGNED_BYTE, atlas.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);
}

float FontRenderer::getTextWidth(const std::string& text, float scale) const {
    return static_cast<float>(text.length()) * 8.0f * scale;
}

float FontRenderer::getTextHeight(float scale) const {
    return 8.0f * scale;
}

void FontRenderer::renderText(const std::string& text, float x, float y, float scale, const glm::vec4& color, bool dropShadow) {
    if (text.empty() || !m_Shader || m_FontTexture == 0 || m_VAO == 0) return;

    glDisable(GL_DEPTH_TEST);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    m_Shader->use();
    glm::mat4 projection = glm::ortho(0.0f, static_cast<float>(m_WindowWidth), static_cast<float>(m_WindowHeight), 0.0f, -1.0f, 1.0f);
    m_Shader->setMat4("u_Projection", projection);
    m_Shader->setBool("u_UseTexture", true);

    if (glActiveTexture) {
        glActiveTexture(GL_TEXTURE0);
    }
    glBindTexture(GL_TEXTURE_2D, m_FontTexture);
    m_Shader->setInt("u_Texture", 0);

    glBindVertexArray(m_VAO);
    glBindBuffer(GL_ARRAY_BUFFER, m_VBO);

    auto renderPass = [&](float posX, float posY, const glm::vec4& renderColor) {
        std::vector<float> vertices;
        vertices.reserve(text.length() * 24);

        float curX = posX;
        float charW = 8.0f * scale;
        float charH = 8.0f * scale;

        for (char c : text) {
            if (c == '\n') {
                posY += charH + 2.0f * scale;
                curX = posX;
                continue;
            }

            int charIdx = static_cast<int>(c) - 32;
            if (charIdx < 0 || charIdx >= 95) charIdx = 0; // fallback to space

            int tileX = charIdx % 16;
            int tileY = charIdx / 16;
            float u0 = (tileX * 8.0f) / 128.0f;
            float v0 = (tileY * 8.0f) / 128.0f;
            float u1 = u0 + (8.0f / 128.0f);
            float v1 = v0 + (8.0f / 128.0f);

            float x0 = curX;
            float y0 = posY;
            float x1 = curX + charW;
            float y1 = posY + charH;

            // Two triangles for glyph quad
            float quad[24] = {
                x0, y1, u0, v1,
                x1, y0, u1, v0,
                x0, y0, u0, v0,

                x0, y1, u0, v1,
                x1, y1, u1, v1,
                x1, y0, u1, v0
            };
            vertices.insert(vertices.end(), std::begin(quad), std::end(quad));

            curX += charW;
        }

        if (!vertices.empty()) {
            m_Shader->setVec4("u_Color", renderColor);
            glBufferSubData(GL_ARRAY_BUFFER, 0, vertices.size() * sizeof(float), vertices.data());
            glDrawArrays(GL_TRIANGLES, 0, static_cast<GLsizei>(vertices.size() / 4));
        }
    };

    // 1. Draw Drop Shadow (offset by 1-2px in dark tone)
    if (dropShadow) {
        float shadowOffset = std::max(1.0f, scale);
        glm::vec4 shadowColor = glm::vec4(color.r * 0.25f, color.g * 0.25f, color.b * 0.25f, color.a);
        renderPass(x + shadowOffset, y + shadowOffset, shadowColor);
    }

    // 2. Draw Foreground text
    renderPass(x, y, color);

    glBindVertexArray(0);
    glBindTexture(GL_TEXTURE_2D, 0);
    glDisable(GL_BLEND);
    glEnable(GL_DEPTH_TEST);
}

